CREATE TABLE `release_acceptances` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `project_id` BIGINT NOT NULL,
  `build_version` VARCHAR(80) NOT NULL,
  `verdict` VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `reviewer_id` BIGINT NOT NULL,
  `reviewer_name` VARCHAR(80) NOT NULL,
  `notes` VARCHAR(2000) NULL DEFAULT NULL,
  `created_at` DATETIME(6) NOT NULL,
  `request_key` BINARY(16) NOT NULL,
  `run_count` SMALLINT UNSIGNED NOT NULL,
  `unclosed_defect_count` INT UNSIGNED NOT NULL,
  `defect_scope` VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `evidence` JSON NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_release_acceptance_request` (`project_id`, `reviewer_id`, `request_key`),
  KEY `ix_release_acceptances_project_id` (`project_id`, `id`),
  KEY `ix_release_acceptances_reviewer_id` (`reviewer_id`),
  CONSTRAINT `fk_release_acceptances_project` FOREIGN KEY (`project_id`) REFERENCES `projects` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `fk_release_acceptances_reviewer` FOREIGN KEY (`reviewer_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `ck_release_acceptances_build` CHECK (CHAR_LENGTH(TRIM(`build_version`)) > 0),
  CONSTRAINT `ck_release_acceptances_verdict` CHECK (`verdict` IN ('APPROVED','REJECTED')),
  CONSTRAINT `ck_release_acceptances_runs` CHECK (`run_count` BETWEEN 1 AND 50),
  CONSTRAINT `ck_release_acceptances_defect_scope` CHECK (`defect_scope` = 'ALL_PROJECT_UNCLOSED_AT_CAPTURE')
) ENGINE=InnoDB ROW_FORMAT=DYNAMIC DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
